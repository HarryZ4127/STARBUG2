#!/usr/bin/env python3
"""Summarise dse.py output into results/dse/: factorial.csv, main_effects.csv, sensitivity.csv,
compiler.csv and SUMMARY.md (the tables quoted in docs/07 and docs/08).

Speedups are geomeans over the 16 kernels. Unless a column says otherwise the baseline is SB1
(4-wide, one memory op in lane 0, no predictor) running the *same* code variant, scheduled by
the model's list scheduler with oracle alias information. "vs RV32GC" columns divide the -O3
scalar build on the 1-wide RV32GC baseline by the configuration's cycles."""
import collections
import csv
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
H = os.path.expanduser(os.environ.get("STARBUG_HOME", "~/starbug"))
if not os.path.exists(f"{H}/dse_factorial.json"):
    H = os.path.join(HERE, "results", "raw")  # the committed copies of the 2026-10-16 run
OUT = os.path.join(HERE, "results", "dse")
os.makedirs(OUT, exist_ok=True)
SB1 = "SB1 today: 4-wide, 1 mem op (lane 0), no predictor"
RV = "RV32GC baseline: 1-wide, gshare"
GROUPS = ("float DSP (team Embench suite)", "integer DSP / ML", "ALU / control")
SHORT = {"float DSP (team Embench suite)": "float DSP", "integer DSP / ML": "int DSP/ML", "ALU / control": "ALU/control"}


def gmean(xs):
    xs = list(xs)
    return math.exp(sum(math.log(x) for x in xs) / len(xs))


def speedups(res, cfg, base_cfg=SB1, base_res=None):
    base_res = base_res or res
    return {b: base_res[b][base_cfg]["cycles"] / res[b][cfg]["cycles"] for b in res}


def by_group(sp, group):
    out = {"all": gmean(sp.values())}
    for g in GROUPS:
        out[SHORT[g]] = gmean(v for b, v in sp.items() if group[b] == g)
    return out


def md_table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---" for _ in header) + "|\n"
    for r in rows:
        s += "| " + " | ".join(f"{x:.2f}" if isinstance(x, float) else str(x) for x in r) + " |\n"
    return s


def write_csv(name, rows):
    with open(f"{OUT}/{name}", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


md = ["# STARBUG 2 design-space exploration: summary tables",
      "",
      "Generated by `mpact_run/dse_summary.py` from `dse.py` output. Speedups are geomeans over 16 "
      "kernels; the baseline is SB1 running the same code unless the column says otherwise. "
      "Interpretation and caveats: `docs/07-design-space-exploration.md`.", ""]

# ---------------------------------------------------------------- factorial
F = json.load(open(f"{H}/dse_factorial.json"))
group = F["group"]
U, S = F["results"]["unroll"], F["results"]["scalar"]
refs = F["refs"]
rows = []
for c in F["configs"]:
    if c in (SB1, RV):
        continue
    w, mem, bank, br, zol = [x.strip() for x in c.split("|")]
    su, ss = speedups(U, c), speedups(S, c)
    gu = by_group(su, group)
    row = dict(config=c, width=int(w[1:]), memory=mem, banks=bank, branch=br, zol=zol,
               speedup_unroll=round(gu["all"], 4), **{f"unroll_{k}": round(v, 4) for k, v in gu.items() if k != "all"},
               speedup_O3=round(gmean(ss.values()), 4),
               vs_rv32gc_unroll=round(gmean(refs[b]["scalar_rv32gc"] / U[b][c]["cycles"] for b in U), 4),
               vs_rv32gc_O3=round(gmean(refs[b]["scalar_rv32gc"] / S[b][c]["cycles"] for b in S), 4))
    rows.append(row)
write_csv("factorial.csv", rows)
rows.sort(key=lambda r: -r["speedup_unroll"])
best = rows[0]["speedup_unroll"]
sb1_vs_rv = gmean(refs[b]["scalar_rv32gc"] / U[b][SB1]["cycles"] for b in U)
sb1_vs_rv_o3 = gmean(refs[b]["scalar_rv32gc"] / S[b][SB1]["cycles"] for b in S)
md += ["## 1. Full factorial (unrolled code)", "",
       f"{len(rows)} configurations = width {{2,4,6,8}} x memory {{1LS, 1LS+1LO, 2LS, 2LS+2LO}} x banks "
       "{ideal, 2, 4} x branch {none, BTFN, gshare} x ZOL {off, on} (invalid or duplicate combinations removed). "
       f"SB1 itself is {sb1_vs_rv:.2f}x RV32GC -O3 scalar on unrolled code and {sb1_vs_rv_o3:.2f}x on -O3 code.", "",
       "### Top 15", ""]
md.append(md_table(["config", "all", "float DSP", "int DSP/ML", "ALU/control", "-O3 code", "vs RV32GC"],
                   [[r["config"], r["speedup_unroll"], r["unroll_float DSP"], r["unroll_int DSP/ML"],
                     r["unroll_ALU/control"], r["speedup_O3"], r["vs_rv32gc_unroll"]] for r in rows[:15]]))
# smallest designs within x% of the best
md += ["", "### Cheapest configuration reaching a share of the best", "",
       "Cheapest = fewest lanes, then fewest memory paths, then fewest banks (ideal banks count as "
       "the most expensive, since they need a multi-ported memory), then the simplest branch handling.", ""]
MEMRANK = {"1LS": 0, "1LS+1LO": 1, "2LS": 2, "2LS+2LO": 3}
BANKRANK = {"ideal": 3, "2 banks": 1, "4 banks": 2}
BRRANK = {"none": 0, "btfn": 1, "gshare": 2}
trows = []
for share in (0.80, 0.90, 0.95, 0.99):
    ok = [r for r in rows if r["speedup_unroll"] >= share * best]
    ok.sort(key=lambda r: (r["width"], MEMRANK[r["memory"]], BANKRANK[r["banks"]] if r["memory"] != "1LS" else 0,
                           BRRANK[r["branch"]], r["zol"] == "ZOL"))
    r = ok[0]
    trows.append([f"{share:.0%}", r["config"], r["speedup_unroll"]])
md.append(md_table(["share of best", "cheapest config", "speedup"], trows))

# main effects: geomean over all other factors, per level
eff = []
for fac in ("width", "memory", "banks", "branch", "zol"):
    lv = collections.defaultdict(list)
    for r in rows:
        if fac == "banks" and r["memory"] == "1LS":
            continue
        lv[r[fac]].append(r["speedup_unroll"])
    for k, v in lv.items():
        eff.append(dict(factor=fac, level=k, n=len(v), geomean=round(gmean(v), 4), best=round(max(v), 4)))
write_csv("main_effects.csv", eff)
md += ["", "### Main effects", "",
       "Geomean (over all other factor settings) of the configuration speedups, per factor level. "
       "Banks exclude 1LS (no conflicts possible).", ""]
md.append(md_table(["factor", "level", "configs", "geomean speedup", "best"],
                   [[e["factor"], e["level"], e["n"], e["geomean"], e["best"]] for e in eff]))

# width x memory interaction at the best branch setting
md += ["", "### Width x memory paths (gshare + ZOL)", ""]
cells = {(r["width"], r["memory"], r["banks"]): r["speedup_unroll"] for r in rows
         if r["branch"] == "gshare" and r["zol"] == "ZOL"}
MEMORY_ORDER = ["1LS", "1LS+1LO", "2LS", "2LS+2LO"]
hdr = ["lanes", "1LS"] + [f"{m} {b}" for m in MEMORY_ORDER[1:] for b in ("ideal", "4 banks", "2 banks")]
tr = []
for w in (2, 4, 6, 8):
    row = [w, cells.get((w, "1LS", "ideal"), "-")]
    for m in MEMORY_ORDER[1:]:
        for b in ("ideal", "4 banks", "2 banks"):
            row.append(cells.get((w, m, b), "-"))
    tr.append(row)
md.append(md_table(hdr, tr))

# O3 vs unroll
md += ["", "### Same hardware, plain -O3 code", "",
       "Speedup over SB1 when the compiler does not unroll (each column on its own code).", ""]
pick = ["w4 | 1LS | ideal | gshare | no ZOL", "w4 | 1LS | ideal | none | ZOL",
        "w4 | 1LS+1LO | 2 banks | none | no ZOL", "w4 | 1LS+1LO | 2 banks | gshare | ZOL",
        "w8 | 2LS | 2 banks | gshare | ZOL", "w8 | 2LS+2LO | ideal | gshare | ZOL"]
byname = {r["config"]: r for r in rows}
md.append(md_table(["config", "unrolled code", "-O3 code", "unrolled vs RV32GC", "-O3 vs RV32GC"],
                   [[p, byname[p]["speedup_unroll"], byname[p]["speedup_O3"], byname[p]["vs_rv32gc_unroll"],
                     byname[p]["vs_rv32gc_O3"]] for p in pick if p in byname]))

# ---------------------------------------------------------------- sensitivity
Sx = json.load(open(f"{H}/dse_sensitivity.json"))
SU, SS = Sx["results"]["unroll"], Sx["results"]["scalar"]
srows = []
for c in Sx["configs"]:
    if c == RV:
        continue
    an, fac, lab = [x.strip() for x in c.split("|")]
    anchor = f"{an} | anchor | -"
    su = speedups(SU, c, anchor)
    so = speedups(SS, c, anchor)
    gu = by_group(su, group)
    srows.append(dict(anchor=an, factor=fac, setting=lab, vs_anchor_unroll=round(gu["all"], 4),
                      **{f"vs_anchor_{k}": round(v, 4) for k, v in gu.items() if k != "all"},
                      vs_anchor_O3=round(gmean(so.values()), 4),
                      vs_SB1_unroll=round(gmean(speedups(SU, c, "SB1 | anchor | -").values()), 4)))
write_csv("sensitivity.csv", srows)
md += ["", "## 2. One knob at a time", "",
       "Each row changes one thing on the anchor. `vs anchor` < 1 means slower. SB2 candidate = 4-wide, "
       "1 LS + 1 load-only path, 2 word-interleaved banks, gshare, zero-overhead loops.", ""]
for an in ("SB1", "SB2 candidate"):
    md += [f"### Around {an}", ""]
    md.append(md_table(["factor", "setting", "vs anchor", "float DSP", "int DSP/ML", "ALU/control", "-O3 code"],
                       [[r["factor"], r["setting"], r["vs_anchor_unroll"], r["vs_anchor_float DSP"],
                         r["vs_anchor_int DSP/ML"], r["vs_anchor_ALU/control"], r["vs_anchor_O3"]]
                        for r in srows if r["anchor"] == an and r["factor"] != "anchor"]))
    md.append("")

# ---------------------------------------------------------------- compiler
C = json.load(open(f"{H}/dse_compiler.json"))
crows = []
base_u = C["results"]["unroll | alias oracle"]
for v, res in C["results"].items():
    for c in C["configs"]:
        if c == SB1:
            continue
        m, s = [x.strip() for x in c.split("|")]
        sp = {b: refs[b]["scalar_rv32gc"] / res[b][c]["cycles"] for b in res}
        crows.append(dict(code=v.split(" | ")[0], alias=v.split(" | ")[1].replace("alias ", ""), machine=m,
                          scheduler=s, vs_rv32gc=round(gmean(sp.values()), 4),
                          **{f"vs_rv32gc_{SHORT[g]}": round(gmean(x for b, x in sp.items() if group[b] == g), 4)
                             for g in GROUPS},
                          vs_SB1_list_unroll=round(gmean(base_u[b][SB1]["cycles"] / res[b][c]["cycles"] for b in res), 4)))
write_csv("compiler.csv", crows)
md += ["## 3. Compiler strategy", "",
       "Speedup over -O3 scalar code on RV32GC. `greedy packetizer` mimics the current LLVM "
       "StarbugVLIWPacketizer (fills packets in program order, memory op first, ignores latency); "
       "`list scheduler` is latency-aware critical-path list scheduling; `+ modulo scheduling` "
       "is the MII lower bound for single-block loops. `alias none` = no memory disambiguation "
       "inside a block (no `restrict`, no alias analysis).", ""]
md.append(md_table(["code", "alias", "machine", "scheduler", "vs RV32GC", "float DSP", "int DSP/ML", "ALU/control"],
                   [[r["code"], r["alias"], r["machine"], r["scheduler"], r["vs_rv32gc"], r["vs_rv32gc_float DSP"],
                     r["vs_rv32gc_int DSP/ML"], r["vs_rv32gc_ALU/control"]] for r in crows]))
dsp = [b for b in refs if "hand_vliw_sb1" in refs[b]]
hand = gmean(refs[b]["scalar_rv32gc"] / refs[b]["hand_vliw_sb1"] for b in dsp)
md += ["", "### Hand-written VLIW kernels vs modelled compilers (float DSP suite, SB1)", "",
       f"Hand-VLIW as written, on SB1: **{hand:.2f}x** RV32GC -O3 scalar (geomean of {len(dsp)} kernels).", ""]
hr = []
for v in ("unroll | alias oracle", "scalar | alias oracle", "unroll | alias none"):
    for s in ("greedy packetizer", "list scheduler", "list + modulo scheduling"):
        c = f"SB1 | {s}"
        hr.append([v, s, gmean(refs[b]["scalar_rv32gc"] / C["results"][v][b][c]["cycles"] for b in dsp)])
md.append(md_table(["code / alias", "scheduler", "vs RV32GC (float DSP)"], hr))

open(f"{OUT}/SUMMARY.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
